"""Run all four algorithms on common random scenarios and persist results."""
from __future__ import annotations
import csv
import json
import os
from pathlib import Path
from typing import List, Dict
import numpy as np
from .algorithms import ALGORITHMS, run_algorithm
from .config import SimulationConfig
from .scenario import generate_scenario
from .plotting import create_all_figures


def _write_csv(path: Path, rows: List[Dict]):
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def _aggregate(per_seed: List[Dict]) -> List[Dict]:
    metric_keys = [k for k in per_seed[0] if k not in ("algorithm", "seed")]
    summary = []
    for algorithm in ALGORITHMS:
        rows = [r for r in per_seed if r["algorithm"] == algorithm]
        item = {"algorithm": algorithm, "runs": len(rows)}
        for key in metric_keys:
            vals = np.asarray([r[key] for r in rows], dtype=float)
            item[f"{key}_mean"] = float(np.nanmean(vals))
            item[f"{key}_std"] = float(np.nanstd(vals, ddof=1)) if len(vals) > 1 else 0.0
        summary.append(item)
    return summary


def run_experiments(cfg: SimulationConfig, output_dir: str | Path, verbose: bool = True):
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "figures").mkdir(exist_ok=True)
    per_seed_rows: List[Dict] = []
    timeseries_rows: List[Dict] = []

    if verbose:
        print("NDT-TJO comparative simulation")
        print(f"UAVs={cfg.n_uavs}, users={cfg.n_users}, RBs={cfg.n_rbs}, slots={cfg.slots}, seeds={cfg.seeds}")
        print("Generating common synthetic traces and running CRA, TTJO, NDT-O and NDT-TJO...\n")

    for seed in range(cfg.seeds):
        scenario = generate_scenario(cfg, seed=seed)
        for algorithm in ALGORITHMS:
            result, series = run_algorithm(algorithm, scenario, cfg)
            per_seed_rows.append(result)
            for row in series:
                row = dict(row)
                row["algorithm"] = algorithm
                row["seed"] = seed
                timeseries_rows.append(row)
            if verbose:
                print(
                    f"seed {seed + 1:02d}/{cfg.seeds:02d} | {algorithm:6s} | "
                    f"objective={result['objective_mean']:.4f} | "
                    f"admission={result['admission_rate_pct']:.1f}% | "
                    f"SLA violations={result['latency_violation_rate_pct']:.1f}%"
                )

    summary = _aggregate(per_seed_rows)
    _write_csv(out / "per_seed_metrics.csv", per_seed_rows)
    _write_csv(out / "summary.csv", summary)
    _write_csv(out / "timeseries.csv", timeseries_rows)
    with (out / "simulation_config.json").open("w", encoding="utf-8") as f:
        json.dump(cfg.to_dict(), f, indent=2)

    create_all_figures(out)
    _write_summary_text(out / "RESULTS_OVERVIEW.txt", summary, cfg)
    _write_paper_helpers(out, summary, cfg)
    if verbose:
        print("\nCompleted. Outputs saved to:", out.resolve())
        print("- summary.csv and per_seed_metrics.csv")
        print("- timeseries.csv")
        print("- figures/*.png")
        print("- RESULTS_OVERVIEW.txt")
    return summary


def _write_summary_text(path: Path, summary: List[Dict], cfg: SimulationConfig):
    columns = [
        ("objective_mean_mean", "Objective"),
        ("energy_mean_j_per_slot_mean", "Mean energy (J/slot)"),
        ("admission_rate_pct_mean", "Admission rate (%)"),
        ("latency_violation_rate_pct_mean", "SLA violation rate (%)"),
        ("avg_queue_bits_mean", "Average queue (bits)"),
        ("nominal_pass_then_violate_pct_mean", "NDT false-accept rate (%)"),
    ]
    lines = [
        "NDT-TJO COMPARATIVE SIMULATION - RESULTS OVERVIEW",
        "=================================================",
        f"Runs: {cfg.seeds} seeds; slots per run: {cfg.slots}; users: {cfg.n_users}; UAVs: {cfg.n_uavs}",
        "All values are generated by the bundled synthetic simulator; see ASSUMPTIONS_AND_SCOPE.md.",
        "",
    ]
    for row in summary:
        lines.append(row["algorithm"])
        for key, label in columns:
            val = row.get(key, float("nan"))
            lines.append(f"  {label}: {val:.4f}")
        lines.append("")
    by_alg = {row["algorithm"]: row for row in summary}
    ndto = by_alg.get("NDT-O")
    tjo = by_alg.get("NDT-TJO")
    if ndto and tjo:
        def pct_change(a, b):
            a, b = float(a), float(b)
            return 100.0 * (b - a) / abs(a) if abs(a) > 1e-12 else 0.0
        lines.extend([
            "NDT-O to NDT-TJO paired-summary comparison (percentage change in aggregate means):",
            f"  Objective: {pct_change(ndto['objective_mean_mean'], tjo['objective_mean_mean']):+.2f}% (positive means higher cost)",
            f"  Admission rate: {pct_change(ndto['admission_rate_pct_mean'], tjo['admission_rate_pct_mean']):+.2f}%",
            f"  SLA violation rate: {pct_change(ndto['latency_violation_rate_pct_mean'], tjo['latency_violation_rate_pct_mean']):+.2f}%",
            f"  Average queue backlog: {pct_change(ndto['avg_queue_bits_mean'], tjo['avg_queue_bits_mean']):+.2f}%",
            f"  NDT false-accept rate: {pct_change(ndto['nominal_pass_then_violate_pct_mean'], tjo['nominal_pass_then_violate_pct_mean']):+.2f}%",
            "",
        ])
    lines.extend([
        "Interpretation notes:",
        "- Lower objective, energy, queue backlog and SLA violation rate are generally preferable.",
        "- Higher admission rate and service utility are generally preferable, provided constraints hold.",
        "- The NDT false-accept metric compares nominally accepted actions with the synthetic latent-latency trace; it is not a field measurement.",
        "- Robust screening can trade admission/utility and objective value for lower constraint risk.",
        "- These outputs are simulation results under documented assumed parameters, not field measurements.",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


